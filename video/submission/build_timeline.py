"""Turn the measured VO durations into the film's beat grid.

Writes `build/timeline.json` (read by make_audio.py) and `timeline.js` (read by film.js),
so picture and sound share one set of numbers instead of two hand-typed copies.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"

LEAD_IN = 1.0
GAP = 0.7
TAIL = 3.1

vo = json.loads((BUILD / "vo.json").read_text())

beat_starts = []
t = LEAD_IN
for beat in vo["beats"]:
    beat_starts.append(round(t, 3))
    t += beat["duration"] + GAP

total = round(beat_starts[-1] + vo["beats"][-1]["duration"] + TAIL, 3)

# Scene boundaries sit just before each VO beat, so the morph leads the voice.
scenes = []
for i, (start, beat) in enumerate(zip(beat_starts, vo["beats"])):
    scenes.append({
        "id": beat["id"],
        "start": round(max(0.0, start - (0.55 if i else 0.0)), 3),
        "vo": start,
        "end": round(start + beat["duration"], 3),
        "line": beat["text"],
    })

timeline = {
    "duration": total,
    "beats": [s["vo"] for s in scenes],
    "sceneStarts": [s["start"] for s in scenes],
    "sceneEnds": [s["end"] for s in scenes],
    "scenes": scenes,
    # Shared marks: the pictures and the sound design both read these.
    "marks": {
        "letterOn": 0.25,
        "redact1": 12.0,
        "redact2": 15.4,
        "statLine": 19.3,
        "shutter": round(beat_starts[2] + 2.4, 3),
        "seal": round(beat_starts[2] + 6.2, 3),
        "scanIn": round(beat_starts[3] + 1.0, 3),
        "checks": [round(beat_starts[3] + 3.4 + i * 0.95, 3) for i in range(12)],
        "zeroBytes": round(beat_starts[3] + 14.2, 3),
        "resultsIn": round(beat_starts[4] + 1.2, 3),
        "quoteReveal": round(beat_starts[5] + 3.0, 3),
        "askType": round(beat_starts[5] + 5.0, 3),
        "answer1": round(beat_starts[5] + 8.0, 3),
        "answer2": round(beat_starts[5] + 11.6, 3),
        "receiptIn": round(beat_starts[6] + 1.0, 3),
        "signature": round(beat_starts[6] + 3.4, 3),
        "forget": round(beat_starts[7] + 1.6, 3),
        "wordmark": round(beat_starts[7] + 8.4, 3),
    },
}

(BUILD / "timeline.json").write_text(json.dumps(timeline, indent=2) + "\n")
(ROOT / "timeline.js").write_text(
    "// Generated by build_timeline.py from the measured ElevenLabs durations.\n"
    "// A classic script on purpose: the page is loaded over file://, where ES modules are blocked.\n"
    "window.TL = " + json.dumps(timeline, indent=2) + ";\n"
)
print(f"duration {total:.3f}s")
for s in scenes:
    print(f"  {s['id']}  scene {s['start']:6.2f}  vo {s['vo']:6.2f}  end {s['end']:6.2f}")
